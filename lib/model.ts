// Token Radar's value model: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the watchlist's own rule would keep:
// the 40 watchlist slugs, the pre-token protocols below the $50M floor, and the
// pre-token protocols above the floor the watchlist leaves out (their DefiLlama
// record names a parent protocol, which this snapshot does not carry, so the
// board scores them on the figures it can see). A protocol is pre-token when
// its record carries no token at all: no market cap, no CoinGecko id, no symbol.
//
// A protocol is kept out of the ranked board when it is a wrapped, staked or
// bridged product of a token that already trades, a versioned pool of another
// protocol, or an exchange product: the same rule the watchlist uses, applied
// to the whole snapshot. Those protocols are not launches waiting to happen;
// WBTC is Bitcoin on Ethereum, not a protocol still to issue a token.
//
// Implied value is calibrated from the snapshot itself, never from a list of
// names. The 129 protocols whose token already trades carry both a market cap
// and a TVL, so each category's mcap/TVL ratio is a market fact: the median
// ratio in a category is that sector's multiple, shrunk toward the global
// median (prior weight 5) and clamped to [0.02, 2.0] so a thin category with
// one wild outlier cannot set the price. A category with no trading protocol
// takes the global median. Then:
//
//   sector   = calibrated multiple for the protocol's category
//   base     = tvl_usd x sector
//   growth   = clamp(change_7d, -60, 120) per cent (unreported: 0)
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity = 0.7 + 0.3 x min(age_days, 1460) / 1460   (age unknown: 365)
//   implied  = max(1, round(base x growthMult x maturity))
//
// Age is the time since DefiLlama first listed the protocol: the record of how
// long it has run with no token. Growth is capped because a 7-day jump of
// thousands of per cent is a data quirk, not a trend. No protocol name is ever
// special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

